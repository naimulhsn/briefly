/**
 * Source catalog. Prefer native RSS. When a site has no reliable feed
 * (or blocks bots with a challenge page), fall back to a Google News
 * site search, which still attributes the original outlet.
 */
function gnews(query, lang = "en") {
  const hl = lang === "bn" ? "bn-BD" : "en-BD";
  const ceid = lang === "bn" ? "BD:bn" : "BD:en";
  const q = encodeURIComponent(query);
  return `https://news.google.com/rss/search?q=${q}&hl=${hl}&gl=BD&ceid=${ceid}`;
}

